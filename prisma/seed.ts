async function main() {
  const existingAdmin = await db.user.findFirst({ where: { role: "ADMIN" } });
  if (!existingAdmin) {
    const email = process.env.BOOTSTRAP_ADMIN_EMAIL?.trim().toLowerCase();
    const password = process.env.BOOTSTRAP_ADMIN_PASSWORD;
    if (!email || !password || password.length < 12) throw new Error("Set BOOTSTRAP_ADMIN_EMAIL and BOOTSTRAP_ADMIN_PASSWORD of at least 12 characters");
    await db.user.create({ data: { email, passwordHash: await hashPassword(password), firstName: "Администратор", lastName: "Сайта", role: "ADMIN", emailVerifiedAt: new Date() } });
    console.log(`Administrator created: ${email}`);
  }

  for (const page of pages) {
    const existing = await db.page.findUnique({ where: { slug: page.slug } });
    if (existing?.body.includes("Администратор сайта обязан")) {
      await db.page.update({ where: { slug: page.slug }, data: { body: page.body } });
    } else {
      await db.page.upsert({ where: { slug: page.slug }, create: { seoTitle: null, seoDescription: null, ...page }, update: {} });
    }
  }

  const settings = await db.siteSettings.upsert({
    where: { id: 1 },
    create: { phone: "", email: "info@doctor-androlog.ru", address: "163001, Архангельская обл., г. Архангельск, ул. Суворова, 1", workHours: "Пн–Пт: 9:00–18:00" },
    update: {},
  });
  await db.organizationInfo.upsert({
    where: { id: 1 },
    create: {
      fullName: "ГБУЗ Архангельской области «Первая ГКБ им. Е. Е. Волосевич»",
      shortName: "Архангельский региональный урологический центр",
      legalAddress: settings.address,
      actualAddress: settings.address,
      appointmentInfo: "Порядок записи уточняйте по телефону или через администратора отделения.",
    },
    update: {},
  });
  console.log(`Seed complete: ${pages.length} editable pages`);
}

